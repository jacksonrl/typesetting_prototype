import 'package:typesetting_prototype/typesetting_prototype.dart';

void main() async {
  print("Generating simple_test.pdf...");

  final doc = Document(
    debug: true,
    body: PageLayout(
      body: [
        FormattedText('''
          #let title = "Typesetting Script Demo"
          #let subTitle = "Pure script generation"
          
          #Text(title, fontSize: 24, style: #TextStyle(fontWeight: #FontWeight.bold))
          #Text(subTitle, fontSize: 14, style: #TextStyle(yOffsetFactor: 0.2))

          #SizedBox(height: 20)

          #Text("Below are examples of reusable components defined entirely in the script:")
          
          #SizedBox(height: 10)

          #Row[
            #SizedBox(width: 10)
          ]

          #SizedBox(height: 20)

          #let footerNote = "Generated by the new ScriptEngine."
          
          #FlowFill[ #SizedBox(height: 0) ]
          
          #DecoratedBox(decoration: #BoxDecoration(border: #Border.all(width: 0.5)))[
             #Padding(padding: #EdgeInsets.symmetric(horizontal: 5, vertical: 2), child: #Text(footerNote, fontSize: 8))
          ]
        '''),
      ],
    ),
  );

  await PdfGenerator.generatePdf(doc, 'simple_test.pdf');
}