import 'package:typesetting_prototype/typesetting_prototype.dart';

void main() async {
  print("Generating simple_test.pdf...");

  final doc = Document(
    debug: true,
    body: PageLayout(
      body: [
        FormattedText('''
          #let title = "Typesetting Script Demo"
          
          #Text(title, fontSize: 24, style: TextStyle(fontWeight: FontWeight.bold))
          
          #SizedBox(height: 20)

          This is raw text written directly in the script. I did not need to wrap this 
          in a Text widget. The parser automatically consumes this block until it hits 
          a double newline or a code block.

          This is a second paragraph. It was created simply by leaving a blank line 
          above. Single newlines within the editor 
          are converted to spaces, so this text flows naturally.

          #SizedBox(height: 20)

          #let card = (label, *content) => {            
            DecoratedBox(
              decoration: BoxDecoration(border: Border.all(width: 1.0)),
              Padding(
                padding: EdgeInsets.all(10),
                Column(
                    Text(label, style: TextStyle(fontWeight: FontWeight.bold, fontSize: 10))
                    SizedBox(height: 5)
                    content
                    [and my text]
                )
              )
            )
          }

          #Text("Below is a Row mixing text and components:")
          
          #SizedBox(height: 10)

          #Row[
            Start Text
            
            #SizedBox(width: 15)
            
            #card(
              label: "Dynamic Widget"
              [I am a card.]
            )
            
            #SizedBox(width: 15)
            
            End Text
          ]

          #SizedBox(height: 20)

          #DecoratedBox(
             decoration: BoxDecoration(border: Border.all(width: 0.5)),
            Padding(
               padding: EdgeInsets.symmetric(horizontal: 5, vertical: 2), 
               [Generated by the new ScriptEngine.]
             )
          )
        '''),
      ],
    ),
  );

  await PdfGenerator.generatePdf(doc, 'simple_test.pdf');
  print("Done.");
}