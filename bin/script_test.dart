import 'package:typesetting_prototype/typesetting_prototype.dart';

void main() async {
  print("Generating simple_test.pdf...");

  final doc = Document(
    debug: true,
    body: PageLayout(
      body: [
        FormattedText('''
          #let title = "Typesetting Script Demo"
          #let subTitle = "Pure script generation"
          
          #Text(title, fontSize: 24, style: #TextStyle(fontWeight: #FontWeight.bold))
          #Text(subTitle, fontSize: 14, style: #TextStyle(yOffsetFactor: 0.2))

          #SizedBox(height: 20)

          #let card = (label, content) => {
            #DecoratedBox(
              decoration: #BoxDecoration(border: #Border.all(width: 1.0)),
              child: #Padding(
                padding: #EdgeInsets.all(10),
                child: #Column[
                  #Text(label, style: #TextStyle(fontWeight: #FontWeight.bold, fontSize: 10))
                  #SizedBox(height: 5)
                  #content  
                ]
              )
            )
          }

          #Text("Below are examples of reusable components defined entirely in the script:")
          
          #SizedBox(height: 10)

          #Row[
            #card(label: "Card A", content: #Text("This is the first card content."))
            #SizedBox(width: 10)
            #card(label: "Card B", content: #Text("This is the second card, side-by-side."))
          ]

          #SizedBox(height: 20)

          #let footerNote = "Generated by the new ScriptEngine."
          
          #FlowFill[ #SizedBox(height: 0) ]
          
          #DecoratedBox(
             decoration: #BoxDecoration(border: #Border.all(width: 0.5)),
             child: #Padding(
               padding: #EdgeInsets.symmetric(horizontal: 5, vertical: 2), 
               child: #Text(footerNote, fontSize: 8)
             )
          )
        '''),
      ],
    ),
  );

  await PdfGenerator.generatePdf(doc, 'simple_test.pdf');
}